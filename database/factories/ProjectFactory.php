<?php

namespace Database\Factories;

use App\Enums\InvoicingType;
use App\Enums\ProjectStatus;
use App\Models\Company;
use App\Models\Quote;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends \Illuminate\Database\Eloquent\Factories\Factory<\App\Models\Project>
 */
class ProjectFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'company_id' => Company::factory(),
            'quote_id' => Quote::factory(),
            'project_number' => null, // Auto-generated by model
            'status' => ProjectStatus::Active,
            'invoicing_type' => fake()->randomElement([InvoicingType::Single, InvoicingType::Split5050, InvoicingType::Split3070]),
            'start_date' => now()->subDays(rand(1, 30)),
            'completion_date' => null,
            'notes' => fake()->optional()->paragraph(),
        ];
    }

    /**
     * Indicate that the project is completed.
     */
    public function completed(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => ProjectStatus::Completed,
            'completion_date' => now()->subDays(rand(1, 7)),
        ]);
    }

    /**
     * Indicate that the project uses split invoicing (50/50).
     */
    public function splitInvoicing(): static
    {
        return $this->state(fn (array $attributes) => [
            'invoicing_type' => InvoicingType::Split5050,
        ]);
    }
}
