<?php

namespace Database\Factories;

use App\Enums\QuoteProcessingMethod;
use App\Enums\QuoteStatus;
use App\Models\Company;
use App\Models\Lead;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends \Illuminate\Database\Eloquent\Factories\Factory<\App\Models\Quote>
 */
class QuoteFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        $subtotal = fake()->randomFloat(2, 500, 10000);
        $vatAmount = round($subtotal * 0.21, 2);
        $total = $subtotal + $vatAmount;

        return [
            'company_id' => Company::factory(),
            'lead_id' => Lead::factory(),
            'project_id' => null,
            'quote_number' => null, // Auto-generated by model
            'status' => QuoteStatus::Draft,
            'processing_method' => QuoteProcessingMethod::System,
            'valid_until' => now()->addDays(30),
            'subtotal' => $subtotal,
            'vat_amount' => $vatAmount,
            'total' => $total,
            'notes' => fake()->optional()->paragraph(),
            'moneybird_quote_id' => null,
            'sent_at' => null,
            'approved_at' => null,
        ];
    }

    /**
     * Indicate that the quote has been sent.
     */
    public function sent(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => QuoteStatus::Sent,
            'sent_at' => now()->subDays(rand(1, 7)),
        ]);
    }

    /**
     * Indicate that the quote has been approved.
     */
    public function approved(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => QuoteStatus::Approved,
            'sent_at' => now()->subDays(rand(8, 14)),
            'approved_at' => now()->subDays(rand(1, 7)),
        ]);
    }

    /**
     * Indicate that the quote uses Moneybird processing.
     */
    public function withMoneybird(): static
    {
        return $this->state(fn (array $attributes) => [
            'processing_method' => QuoteProcessingMethod::MoneybirdDraft,
            'moneybird_quote_id' => (string) fake()->numberBetween(100000, 999999),
        ]);
    }
}
