<?php

namespace Database\Factories;

use App\Enums\InvoiceStatus;
use App\Enums\InvoiceType;
use App\Models\Company;
use App\Models\Project;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends \Illuminate\Database\Eloquent\Factories\Factory<\App\Models\Invoice>
 */
class InvoiceFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        $subtotal = fake()->randomFloat(2, 500, 10000);
        $vatAmount = round($subtotal * 0.21, 2);
        $total = $subtotal + $vatAmount;

        return [
            'project_id' => Project::factory(),
            'company_id' => Company::factory(),
            'invoice_type' => InvoiceType::Single,
            'status' => InvoiceStatus::Draft,
            'invoice_number' => null, // Auto-generated by model
            'invoice_date' => now()->toDateString(),
            'due_date' => now()->addDays(30)->toDateString(),
            'subtotal' => $subtotal,
            'vat_amount' => $vatAmount,
            'total' => $total,
            'deposit_percentage' => null,
            'moneybird_invoice_id' => null,
            'sent_at' => null,
            'paid_at' => null,
        ];
    }

    /**
     * Indicate that this is a deposit invoice.
     */
    public function deposit(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'invoice_type' => InvoiceType::Deposit,
                'deposit_percentage' => 50.00,
            ];
        });
    }

    /**
     * Indicate that this is a final invoice.
     */
    public function final(): static
    {
        return $this->state(fn (array $attributes) => [
            'invoice_type' => InvoiceType::Final,
        ]);
    }

    /**
     * Indicate that the invoice has been sent.
     */
    public function sent(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => InvoiceStatus::Sent,
            'sent_at' => now()->subDays(rand(1, 14)),
        ]);
    }

    /**
     * Indicate that the invoice has been paid.
     */
    public function paid(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => InvoiceStatus::Paid,
            'sent_at' => now()->subDays(rand(15, 30)),
            'paid_at' => now()->subDays(rand(1, 14)),
        ]);
    }

    /**
     * Indicate that the invoice is synced with Moneybird.
     */
    public function withMoneybird(): static
    {
        return $this->state(fn (array $attributes) => [
            'moneybird_invoice_id' => (string) fake()->numberBetween(100000, 999999),
        ]);
    }
}
